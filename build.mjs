import {readFile,writeFile} from 'node:fs/promises';

// Keep the browser's startup to one script request, without extra packages.
const read=async name=>readFile(new URL(name,import.meta.url),'utf8');
const plain=source=>source.replace(/^import .*?;\s*$/gm,'').replace(/^export /gm,'');
const [calculator,grind,coach,app]=await Promise.all(['calculator.mjs','grind.mjs','grind-ui.js','app.js'].map(read));
const bundle=`// Generated by node build.mjs. Edit the source files instead.\n'use strict';\n(()=>{\n${plain(calculator)}\n${plain(grind)}\nconst setGrindGoal=(()=>{\n${plain(coach)}\nreturn setGrindGoal;\n})();\n${plain(app)}\n})();\n`;
await writeFile(new URL('bundle.js',import.meta.url),bundle);
await writeFile(new URL('project-readme.txt',import.meta.url),await read('README.md'));
console.log('Built bundle.js and the public README.');
